// Generates nuwatt-draft-theme/snippets/breadcrumb-default-trail.liquid from the
// Meteor Mega Menu JSON, using the same "deepest match wins" rule as
// snippets/breadcrumbs.liquid (deepestTreeMatch). Re-run after the Meteor menu changes:
//   node tools/gen-breadcrumb-map.mjs
import { writeFileSync } from 'node:fs';

const SITE = 'https://www.nuwattlighting.com';
const OUT = new URL('../nuwatt-draft-theme/snippets/breadcrumb-default-trail.liquid', import.meta.url);

const html = await (await fetch(`${SITE}/collections/all`)).text();
const m = html.match(/revisionFileUrl:\s*"([^"]+)"/);
if (!m) throw new Error('Meteor revisionFileUrl not found');
const jsonUrl = 'https:' + m[1].replace(/\\\//g, '/');
const tree = await (await fetch(jsonUrl)).json();

const path = (u) => { try { return new URL(u, SITE).pathname.replace(/\/+$/, '').toLowerCase(); } catch { return ''; } };
const filtered = (u) => { try { return [...new URL(u, SITE).searchParams.keys()].some((k) => k.startsWith('filter.')); } catch { return false; } };

// every root-to-node trail, in the same DFS order as collectPaths()
const trails = [];
(function walk(nodes, isRoot, ancestors) {
  for (const n of nodes) {
    const trail = ancestors.concat([{ title: n.name, url: (n.shopifyResource && n.shopifyResource.url) || n.url }]);
    if (!filtered(n.url)) trails.push({ path: path(n.url), trail });
    walk(isRoot ? (n.menu && n.menu.items) || [] : n.items || [], false, trail);
  }
})(tree.navigationItems || [], true, []);

// deepest trail per collection handle; first one found wins a tie (stable sort in the JS)
const best = new Map();
for (const { path: p, trail } of trails) {
  const h = (p.match(/^\/collections\/([^/]+)$/) || [])[1];
  if (!h) continue;
  if (!best.has(h) || trail.length > best.get(h).length) best.set(h, trail);
}

const q = (s) => (s.includes("'") ? `"${s}"` : `'${s}'`);
let out = `{%- comment -%}
  GENERATED by tools/gen-breadcrumb-map.mjs from the Meteor menu JSON - do not edit by hand.
  Default (server-rendered) ancestor trail per collection handle, same "deepest match"
  rule as breadcrumbs.liquid. Outputs "Title|url::Title|url" (ancestors only, nothing if unknown);
  captured by breadcrumbs.liquid.
  ponytail: static copy of the menu - re-run the generator when the Meteor menu changes;
  unknown handles fall back to the live menu lookup in breadcrumbs.liquid.
{%- endcomment -%}
{%- case handle -%}
`;
for (const [h, trail] of [...best].sort()) {
  const anc = trail.slice(0, -1);
  if (anc.some((c) => /[|]|::/.test(c.title))) throw new Error('Delimiter in title: ' + h);
  out += `  {%- when ${q(h)} -%}${anc.map((c) => c.title + '|' + c.url).join('::')}\n`;
}
out += `{%- endcase -%}\n`;
writeFileSync(OUT, out);
console.log(`${best.size} collections -> ${OUT.pathname}`);
